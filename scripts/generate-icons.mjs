/**
 * Generates Gaze's app icon & tray icon as a direct sibling to ../hark:
 *   - Apple Icon Grid: 824x824 continuous superellipse (n=5) on 1024 canvas (100px margin)
 *   - Matte obsidian plate (#141416) with subtle overhead studio depth
 *   - Seamless sculptural L-bracket viewfinder corners + warm porcelain focal dot,
 *     tilted -8 deg, matching Hark's warm ivory-stone metallic facets & lift shadow
 *   - Crisp flat 32px variant & monochrome macOS template tray icon
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const iconsDir = join(rootDir, "src-tauri", "icons");
mkdirSync(iconsDir, { recursive: true });

const C = 512;
const PLATE_A = 412; // 824x824 squircle on 1024 canvas => 100px safe margin
const PLATE_N = 5;
const TILT = -8;
const PLATE_BG = "#141416";
const PAPER = "#FAF9F6";

function squircle(steps = 720) {
  const pts = [];
  for (let i = 0; i < steps; i++) {
    const t = (i / steps) * 2 * Math.PI;
    const ct = Math.cos(t);
    const st = Math.sin(t);
    const x = C + PLATE_A * Math.sign(ct) * Math.abs(ct) ** (2 / PLATE_N);
    const y = C + PLATE_A * Math.sign(st) * Math.abs(st) ** (2 / PLATE_N);
    pts.push(`${x.toFixed(1)} ${y.toFixed(1)}`);
  }
  return `M${pts.join("L")}Z`;
}

/**
 * Single continuous closed SVG path for a sculptural top-left L-bracket with smooth
 * rounded outer corner, rounded arm tips, and a refined curved inner elbow — zero overlap seam.
 */
function lBracketPath(size = 290, thick = 88, rOuter = 40, rTip = 34, rInner = 18) {
  const x0 = -232;
  const y0 = -232;
  const x1 = x0 + size;
  const y1 = y0 + size;
  const xi = x0 + thick;
  const yi = y0 + thick;

  return [
    `M ${x0 + rOuter} ${y0}`,
    `L ${x1 - rTip} ${y0}`,
    `Q ${x1} ${y0} ${x1} ${y0 + rTip}`,
    `L ${x1} ${yi - rTip}`,
    `Q ${x1} ${yi} ${x1 - rTip} ${yi}`,
    `L ${xi + rInner} ${yi}`,
    `Q ${xi} ${yi} ${xi} ${yi + rInner}`,
    `L ${xi} ${y1 - rTip}`,
    `Q ${xi} ${y1} ${xi - rTip} ${y1}`,
    `L ${x0 + rTip} ${y1}`,
    `Q ${x0} ${y1} ${x0} ${y1 - rTip}`,
    `L ${x0} ${y0 + rOuter}`,
    `Q ${x0} ${y0} ${x0 + rOuter} ${y0}`,
    "Z",
  ].join(" ");
}

function buildViewfinderMark({ metal }) {
  const tlFill = metal ? "url(#facet-tl)" : PAPER;
  const brFill = metal ? "url(#facet-br)" : PAPER;
  const dotFill = metal ? "url(#facet-dot)" : PAPER;
  const d = lBracketPath();

  return `
  <g transform="translate(${C} ${C}) rotate(${TILT})"${metal ? ' filter="url(#lift)"' : ""}>
    <path d="${d}" fill="${tlFill}"/>
    <path d="${d}" transform="rotate(180)" fill="${brFill}"/>
    <circle cx="0" cy="0" r="64" fill="${dotFill}"/>
  </g>`;
}

const metalSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Generated by scripts/generate-icons.mjs; edit the script, not this file. -->
  <defs>
    <!-- Matte obsidian plate matching Hark (#141416) with whisper-subtle top light -->
    <radialGradient id="plate-bg" cx="0.35" cy="0.2" r="0.9">
      <stop offset="0%" stop-color="#1E1E21"/>
      <stop offset="55%" stop-color="#141416"/>
      <stop offset="100%" stop-color="#0E0E10"/>
    </radialGradient>
    <!-- Warm porcelain/stone metallic facets directly echoing Hark -->
    <linearGradient id="facet-tl" x1="0.15" y1="0" x2="0.85" y2="1">
      <stop offset="0%" stop-color="#FFFFFF"/>
      <stop offset="100%" stop-color="#D4D0C7"/>
    </linearGradient>
    <linearGradient id="facet-br" x1="0.15" y1="0" x2="0.85" y2="1">
      <stop offset="0%" stop-color="#F3F1EB"/>
      <stop offset="100%" stop-color="#9A968C"/>
    </linearGradient>
    <!-- Luminous warm ivory focal aperture dot -->
    <linearGradient id="facet-dot" x1="0.15" y1="0" x2="0.85" y2="1">
      <stop offset="0%" stop-color="#FFFFFF"/>
      <stop offset="100%" stop-color="#ECE9E0"/>
    </linearGradient>
    <filter id="lift" x="-25%" y="-25%" width="150%" height="160%">
      <feDropShadow dx="0" dy="16" stdDeviation="20" flood-color="#000000" flood-opacity="0.6"/>
    </filter>
  </defs>
  <path d="${squircle()}" fill="url(#plate-bg)"/>
  ${buildViewfinderMark({ metal: true })}
</svg>
`;

const flatSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <path d="${squircle()}" fill="${PLATE_BG}"/>
  ${buildViewfinderMark({ metal: false })}
</svg>
`;

const trayD = lBracketPath(290, 96, 42, 36, 18);
const traySvg = `<svg xmlns="http://www.w3.org/2000/svg" width="44" height="44" viewBox="0 0 1024 1024">
  <g transform="translate(512 512) scale(1.42) rotate(-8)" fill="#18181B">
    <path d="${trayD}"/>
    <path d="${trayD}" transform="rotate(180)"/>
    <circle cx="0" cy="0" r="72"/>
  </g>
</svg>
`;

writeFileSync(join(iconsDir, "appicon.svg"), metalSvg);
writeFileSync(join(iconsDir, "appicon-flat.svg"), flatSvg);
writeFileSync(join(iconsDir, "tray-icon.svg"), traySvg);
console.log("Generated Gaze SVG sources in src-tauri/icons/");
